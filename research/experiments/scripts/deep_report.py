def n(x, nd=0):
    if x is None:
        return "–"
    return f"{x:,.{nd}f}"


def k(x):
    return "–" if x is None else f"{x / 1000:,.0f}k"


def pm(s, nd=0, kilo=False):
    if s["mean"] is None:
        return "–"
    f = (lambda v: k(v)) if kilo else (lambda v: n(v, nd))
    return f"{f(s['mean'])} ± {f(s['std'])} ({f(s['min'])}–{f(s['max'])})"


